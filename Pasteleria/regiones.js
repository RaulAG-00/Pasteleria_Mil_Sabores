// Llena el <select> de regiones. Si venimos de "editar usuario",
// regionGuardada y comunaGuardada dejan seleccionada la opción anterior.
function cargarRegiones(selectRegion, selectComuna, regionGuardada, comunaGuardada) {
    if (!selectRegion || !selectComuna) {
        return;
    }

    selectRegion.innerHTML = '<option value="">Selecciona una región</option>';

    Object.keys(REGIONES_CHILE).forEach(function (region) {
        const opcion = document.createElement("option");
        opcion.value = region;
        opcion.textContent = region;
        selectRegion.appendChild(opcion);
    });

    selectRegion.onchange = function () {
        cargarComunas(selectComuna, selectRegion.value);
    };

    if (regionGuardada) {
        selectRegion.value = regionGuardada;
        cargarComunas(selectComuna, regionGuardada, comunaGuardada);
    } else {
        cargarComunas(selectComuna, "");
    }
}


// Recibe el nombre de la región y arma el <select> de comunas.
function cargarComunas(selectComuna, region, comunaGuardada) {
    selectComuna.innerHTML = '<option value="">Selecciona una comuna</option>';

    const comunas = REGIONES_CHILE[region] || [];

    comunas.forEach(function (comuna) {
        const opcion = document.createElement("option");
        opcion.value = comuna;
        opcion.textContent = comuna;
        selectComuna.appendChild(opcion);
    });

    if (comunaGuardada) {
        selectComuna.value = comunaGuardada;
    }
}
